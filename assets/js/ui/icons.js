/** Replaces `[data-icon]` placeholders in static HTML with the matching icon. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    el.replaceWith(icon(el.dataset.icon, { size: Number(el.dataset.size) || 20 }));
  }
}
